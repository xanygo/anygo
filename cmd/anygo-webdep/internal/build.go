const (
	defaultConfig = "./webdep"
	maxDownload   = int64(128 << 20) // 128 MiB
)

func runBuild(args []string) error {
	flags := flag.NewFlagSet("build", flag.ContinueOnError)
	configPath := flags.String("c", defaultConfig, "configuration file")
	modeOverride := flags.String("mode", "", "build mode: cdn, embed or both")
	debug := flags.Bool("debug", false, "debug: print more detailed logs")
	if err := flags.Parse(args); err != nil {
		return err
	}
	if *debug {
		setupDebug()
	} else {
		xattr.SetRunMode(xattr.ModeProduct)
	}
	cfg, err := loadConfig(*configPath)
	if err != nil {
		return err
	}
	if *modeOverride != "" {
		cfg.Output.Mode = *modeOverride
	}
	if err := normalizeAndValidate(&cfg); err != nil {
		return err
	}

	fmt.Printf("webdep: building mode=%s\n", cfg.Output.Mode)
	b := &builder{
		cfg: cfg,
	}
	if err := b.run(); err != nil {
		return err
	}
	fmt.Printf("webdep: generated %s\n", cfg.Output.Dir)
	return nil
}

type builder struct {
	cfg Config
}

func (bd builder) run() error {
	switch bd.cfg.Output.Mode {
	case "cdn":
		bd.cfg.Output.cleanEmbedFile()
		return bd.buildCDN()
	case "embed":
		bd.cfg.Output.cleanCDNFile()
		return bd.buildEmbed()
	default:
		// todo
		return nil
	}
}

const genCodeHeader = `// Code generated by anygo-webdep; DO NOT EDIT.`

const handlersDocTpl = `
// {{.FnPrefix}}WebdepHandlers 返回 URL 地址前缀与 HTTP Handler 的映射。
// 每个 Handler 负责处理对应地址前缀下的请求。
//
// 例如：
//
//	"/asset/a/": HandlerA,
//	"/asset/b/": HandlerB,
func {{.FnPrefix}}WebdepHandlers() map[string]http.Handler {
`

const cdnTpl1 = `
import (
	"net/http"

	"github.com/xanygo/anygo/xhtml/webdep"
)
`

func (bd builder) writeHandlers(b *strings.Builder) {
	data := map[string]any{
		"FnPrefix": bd.cfg.Output.FnPrefix,
	}
	str, err := xstr.RenderTemplate(handlersDocTpl, data)
	if err != nil {
		panic(err)
	}
	b.WriteString(str)
}

const assetTpl = `
func {{.FnPrefix}}WebdepAssets() []webdep.Asset{
`

func (bd builder) writeAssetFn(b *strings.Builder) error {
	data := map[string]any{
		"FnPrefix": bd.cfg.Output.FnPrefix,
	}
	bf, err := xstr.RenderTemplate(assetTpl, data)
	b.WriteString(string(bf))
	return err
}

func (bd builder) buildCDN() error {
	var sb strings.Builder
	sb.WriteString(genCodeHeader)
	sb.WriteString("\n\npackage ")
	sb.WriteString(bd.cfg.Output.getGoPackage())
	sb.WriteString("\n\n")
	sb.WriteString(cdnTpl1)
	bd.writeHandlers(&sb)
	sb.WriteString("return nil\n}")
	sb.WriteString("\n\n")
	sb.WriteString("\n\nvar webdepCdnAssets = []webdep.Asset{\n")

	for _, a := range bd.cfg.Assets {
		a = a.transCDN(bd.cfg.Sources)
		sb.WriteString(a.GoString())
		sb.WriteString(",\n")
	}
	sb.WriteString("}\n\n")
	bd.writeAssetFn(&sb)
	sb.WriteString("return webdepCdnAssets\n}\n")
	// fmt.Println(sb.String())
	bf, err := format.Source([]byte(sb.String()))
	if err != nil {
		return err
	}
	outfile := bd.cfg.Output.cdnGoFile()
	err = os.WriteFile(outfile, bf, 0644)
	log.Println("output:", filepath.ToSlash(outfile), err)
	return err
}

const embedTpl1 = `
import (
	"embed"
	"io/fs"
	"net/http"

	"github.com/xanygo/anygo/xhtml/webdep"
	"github.com/xanygo/anygo/xhttp"
)

func {{.FnPrefix}}WebdepAssets() []webdep.Asset{
	return webdepEmbedAssets
}

var webdepEmbedAssets = []webdep.Asset{
	`

func (bd builder) buildEmbed() error {
	bd.cfg.Output.cleanEmbedFile()
	if err := bd.downloadResource(); err != nil {
		return err
	}
	var sb strings.Builder
	sb.WriteString(genCodeHeader)
	sb.WriteString("\n\npackage ")
	sb.WriteString(bd.cfg.Output.getGoPackage())
	sb.WriteString("\n\n")

	{
		data := map[string]any{
			"FnPrefix": bd.cfg.Output.FnPrefix,
		}
		bf, err := xstr.RenderTemplate(embedTpl1, data)
		if err != nil {
			return err
		}
		sb.WriteString(string(bf))
	}

	for _, item := range bd.cfg.Assets {
		item = item.transEmbed(bd.cfg.Output.HTTPPrefix, bd.cfg.Sources)
		sb.WriteString(item.GoString())
		sb.WriteString(",\n")
	}
	sb.WriteString("}\n\n")

	bd.buildEmbedDir(&sb)

	bd.buildEmbedArchive(&sb)
	bd.buildEmbedHandlers(&sb)

	// fmt.Println("--------------asset_embed_raw.go-----------------")
	// fmt.Println(sb.String())

	bf, err := format.Source([]byte(sb.String()))
	if err != nil {
		return err
	}
	outfile := bd.cfg.Output.embedGoFile()
	err = os.WriteFile(outfile, bf, 0644)
	log.Println("output:", filepath.ToSlash(outfile), err)
	return err
}

const embedTpl2 = `
//go:embed ` + assetDirName + `
var webdepAssetFiles embed.FS

func webdepEmbedAssetHandler() http.Handler {
	sub, err := fs.Sub(webdepAssetFiles, "` + assetDirName + `")
	if err != nil {
	panic(err)
	}

	return http.FileServer(http.FS(sub))
}
`

func (bd builder) buildEmbedDir(sb *strings.Builder) error {
	if !bd.cfg.hasAssetDir() {
		return nil
	}
	sb.WriteString(embedTpl2)
	return nil
}

func (bd builder) buildEmbedArchive(sb *strings.Builder) error {
	for i, item := range bd.cfg.Sources {
		if item.Archive != nil {
			nameBase := fmt.Sprintf("webdepEmbedArchive_%d", i)

			name1 := nameBase + "_zip"

			sb.WriteString(`//go:embed `)
			sb.WriteString(item.Archive.relName())
			sb.WriteString("\nvar ")
			sb.WriteString(name1)
			sb.WriteString(" []byte\n\n")

			name2 := nameBase + "_hd"

			str := fmt.Sprintf(`
			var %s = &xhttp.ZipFile{
				Content: %s,
			}`, name2, name1)
			sb.WriteString(str)
			sb.WriteString("\n")
		}
	}
	return nil
}

const embedTpl3 = `return  webdepEmbedHandlers
}

var webdepEmbedHandlers=map[string]http.Handler{
`

func (bd builder) buildEmbedHandlers(sb *strings.Builder) error {
	bd.writeHandlers(sb)
	sb.WriteString(embedTpl3)
	urlPrefix := bd.cfg.Output.HTTPPrefix

	prefix0 := urlPrefix + "a/"
	fmt.Fprintf(sb, "%q: http.StripPrefix(%q,webdepEmbedAssetHandler()),\n", prefix0, prefix0)
	for i, item := range bd.cfg.Sources {
		if item.Archive != nil {
			fnName := fmt.Sprintf("webdepEmbedArchive_%d_hd", i)
			prefix1 := urlPrefix + "b/" + item.Name + "/"
			fmt.Fprintf(sb, "%q: http.StripPrefix(%q, %s),\n", prefix1, prefix1, fnName)
		}
	}
	sb.WriteString("\n}\n")
	return nil
}

func (bd builder) downloadResource() error {
	log.Println("download resource ...")
	dir := bd.cfg.Output.Dir
	for _, item := range bd.cfg.Sources {
		if err := item.download(dir); err != nil {
			return err
		}
	}
	return nil
}

func safeRelativeSlashPath(value string) bool {
	if value == "" || strings.Contains(value, "\\") || strings.HasPrefix(value, "/") {
		return false
	}
	clean := path.Clean(value)
	return clean != "." && clean != ".." && !strings.HasPrefix(clean, "../")
}
