const (
	defaultConfig = "webdep.yml"
	maxDownload   = int64(128 << 20) // 128 MiB
)

func runBuild(args []string) error {
	flags := flag.NewFlagSet("build", flag.ContinueOnError)
	configPath := flags.String("c", defaultConfig, "configuration file")
	modeOverride := flags.String("mode", "", "build mode: cdn, embed or both")
	if err := flags.Parse(args); err != nil {
		return err
	}

	cfg, err := loadConfig(*configPath)
	if err != nil {
		return err
	}
	if *modeOverride != "" {
		cfg.Output.Mode = *modeOverride
	}
	if err := normalizeAndValidate(&cfg); err != nil {
		return err
	}

	fmt.Printf("webdep: building mode=%s\n", cfg.Output.Mode)
	b := &builder{
		cfg: cfg,
	}
	if err := b.run(); err != nil {
		return err
	}
	fmt.Printf("webdep: generated %s\n", cfg.Output.Dir)
	return nil
}

type builder struct {
	cfg Config
}

func (b builder) run() error {
	dir := b.cfg.Output.Dir
	if dir == "" {
		return errors.New("empty output dir")
	}
	if err := xfs.KeepDirExists(dir); err != nil {
		return err
	}

	switch b.cfg.Output.Mode {
	case "cdn":
		b.cfg.Output.cleanEmbedFile()
		return b.buildCDN()
	case "embed":
		b.cfg.Output.cleanCDNFile()
		return b.buildEmbed()
	default:
		// todo
		return nil
	}
}

func (b builder) buildCDN() error {
	var sb strings.Builder
	sb.WriteString("// Code generated by anygo-webdep; DO NOT EDIT.\n\n")
	// sb.WriteString("//go:build !webdep_embed\n\n")
	sb.WriteString("package ")
	sb.WriteString(b.cfg.Output.Package)
	sb.WriteString("\n\n")
	sb.WriteString("import (\n")
	sb.WriteString(`"net/http"`)
	sb.WriteString("\n")
	sb.WriteString(`"github.com/xanygo/anygo/xhtml/webdep"`)
	sb.WriteString("\n")
	sb.WriteString(")\n")
	sb.WriteString("\n")
	sb.WriteString("const HasAsset = false\n")
	sb.WriteString(`const Prefix="`)
	sb.WriteString(b.cfg.Output.HandlerPrefix)
	sb.WriteString(`"`)
	sb.WriteString("\n\n")
	sb.WriteString(`func Handler() http.Handler {
	return http.NotFoundHandler()
}`)
	sb.WriteString("\n\nvar cdnAssets = []webdep.Asset{\n")

	for _, a := range b.cfg.Assets {
		a = a.transCDN(b.cfg.Sources)
		sb.WriteString(a.GoString())
		sb.WriteString(",\n")
	}
	sb.WriteString("}\n\n")
	sb.WriteString(`
	func init() {
	webdep.DefaultRegistry.Register(cdnAssets...)
}
	`)
	// fmt.Println(sb.String())
	bf, err := format.Source([]byte(sb.String()))
	if err != nil {
		return err
	}
	outfile := b.cfg.Output.cdnGoFile()
	return os.WriteFile(outfile, bf, 0644)
}

