func (b builder) downloadResource() error {
	dir := b.cfg.Output.Dir
	for _, item := range b.cfg.Sources {
		if err := item.download(dir); err != nil {
			return err
		}
	}
	return nil
}

var client = &http.Client{Timeout: 2 * time.Minute}

func downloadFile(url, workDir string) (string, error) {
	req, err := http.NewRequest(http.MethodGet, url, nil)
	if err != nil {
		return "", err
	}
	req.Header.Set("User-Agent", "webdep/1.0")
	resp, err := client.Do(req)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()
	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		return "", fmt.Errorf("download %s: HTTP %s", url, resp.Status)
	}
	if resp.ContentLength > maxDownload {
		return "", fmt.Errorf("download too large: %d bytes", resp.ContentLength)
	}
	name := path.Base(url)
	tmp, err := os.CreateTemp(workDir, ".download-*-"+name)
	if err != nil {
		return "", err
	}
	defer tmp.Close()
	n, err := io.Copy(tmp, io.LimitReader(resp.Body, maxDownload+1))
	if err != nil {
		return "", err
	}
	if n > maxDownload {
		return "", fmt.Errorf("download exceeds %d bytes", maxDownload)
	}
	return tmp.Name(), nil
}

func downloadArchiveFile(ac *ArchiveConfig, workDir string) error {
	archivePath, err := downloadFile(ac.URL, workDir)
	if err != nil {
		return err
	}
	defer os.Remove(archivePath)
	if ac.SHA256 != "" {
		data, err := os.ReadFile(archivePath)
		if err != nil {
			return err
		}
		sum := sha256.Sum256(data)
		actual := hex.EncodeToString(sum[:])
		expected := strings.ToLower(strings.TrimSpace(ac.SHA256))
		if actual != expected {
			return fmt.Errorf("archive SHA256 mismatch: got %s, want %s", actual, expected)
		}
	}

	zr, err := zip.OpenReader(archivePath)
	if err != nil {
		return fmt.Errorf("open zip: %w", err)
	}
	zr.Close()

	outPath := filepath.Join(workDir, ac.relName())

	if ac.StripComponents > 0 {
		zc := &xcompress.ZipFileStrip{
			Input:           archivePath,
			Output:          outPath,
			StripComponents: ac.StripComponents,
			Overwrite:       true,
			Filter: func(name string) bool {
				bn := path.Base(name)
				return !strings.HasPrefix(bn, ".")
			},
		}
		return zc.Run()
	}

	return xfs.Rename(archivePath, outPath)
}

func safeRelativeSlashPath(value string) bool {
	if value == "" || strings.Contains(value, "\\") || strings.HasPrefix(value, "/") {
		return false
	}
	clean := path.Clean(value)
	return clean != "." && clean != ".." && !strings.HasPrefix(clean, "../")
}

func isGoIdentifier(s string) bool {
	if s == "" {
		return false
	}
	for i, r := range s {
		if i == 0 {
			if !(r == '_' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z') {
				return false
			}
		} else if !(r == '_' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9') {
			return false
		}
	}
	return true
}
